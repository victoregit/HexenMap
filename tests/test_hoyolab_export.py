"""HoYoLAB exporter integration tests: JS browser contracts, payload validation and AppSample compatibility."""
from __future__ import annotations

import json
from pathlib import Path
import shutil
import subprocess
import pytest

from src.live.browser_connector import validated_payload
from src.live.appsample_import import parse_marker_ids, parse_catalog

ROOT = Path(__file__).resolve().parents[1]


@pytest.mark.parametrize('harness', ['hoyolab_contract.cjs', 'hoyolab_popup_contract.cjs'])
def test_hoyolab_browser_contracts(harness):
    """Execute the Node.js simulated browser contract test suite for HoYoLAB."""
    node = shutil.which('node')
    if not node:
        pytest.skip('Node required for HoYoLAB browser contract simulation')
    subprocess.run(
        [node, str(ROOT / 'tests' / harness), str(ROOT)],
        capture_output=True,
        text=True,
        check=True
    )


def test_hoyolab_payload_validation_with_browser_connector():
    """Verify that the payload structure generated by HoYoLAB export strictly conforms to browser_connector."""
    index_path = ROOT / 'extensions' / 'hexen-map-exporter' / 'hoyolab-index.json'
    assert index_path.exists()
    index_data = json.loads(index_path.read_text(encoding='utf-8'))

    # Take a sample of mapped IDs from the index
    sample_ids = list(index_data['mapping'].values())[:20]
    # Filter out any non-numeric markers (e.g. 'ambiguous')
    valid_ids = [i for i in sample_ids if i != 'ambiguous' and i.isdigit()]
    assert len(valid_ids) > 0

    payload = {
        'source': 'appsample',
        'version': 1,
        'markerIds': valid_ids
    }

    validated = validated_payload(payload)
    assert validated['source'] == 'appsample'
    assert validated['version'] == 1
    assert validated['markerIds'] == sorted(set(valid_ids))


@pytest.mark.parametrize('invalid_payload', [
    {'source': 'hoyolab', 'version': 1, 'markerIds': ['100']},  # Wrong source name
    {'source': 'appsample', 'version': 2, 'markerIds': ['100']},  # Wrong version
    {'source': 'appsample', 'version': 1, 'markerIds': ['100'], 'extra': True},  # Extra fields
    {'source': 'appsample', 'version': 1, 'markerIds': ['invalid_id']},  # Non-decimal ID
    {'source': 'appsample', 'version': 1, 'markerIds': [-100]},  # Integer instead of string
    {'source': 'appsample', 'version': 1},  # Missing markerIds
])
def test_hoyolab_payload_rejection_of_invalid_formats(invalid_payload):
    """Ensure browser_connector strictly rejects any malformed, coerced, or non-appsample payloads."""
    with pytest.raises(ValueError):
        validated_payload(invalid_payload)


def test_all_resolved_hoyolab_ids_exist_in_catalog():
    """Strictly verify that 100% of IDs mapped in hoyolab-index.json exist in AppSample catalog."""
    catalog_path = ROOT / 'userData/imports/appsample/catalog-9f0c3fe69094909c/catalog.json'
    assert catalog_path.exists()
    catalog_data = json.loads(catalog_path.read_text(encoding='utf-8'))
    catalog_points = parse_catalog(catalog_data)
    valid_catalog_ids = {p.external_id for p in catalog_points}

    index_path = ROOT / 'extensions' / 'hexen-map-exporter' / 'hoyolab-index.json'
    index_data = json.loads(index_path.read_text(encoding='utf-8'))
    mapping = index_data['mapping']

    mapped_count = 0
    for key, as_id in mapping.items():
        if as_id == 'ambiguous':
            continue
        assert as_id.isdigit(), f"ID must be decimal string: {as_id}"
        assert as_id in valid_catalog_ids, f"ID {as_id} mapped from {key} does not exist in AppSample catalog!"
        mapped_count += 1

    assert mapped_count == 4937, f"Expected 4937 mapped points, got {mapped_count}"


def test_phase_a_multimap_partitioning_and_isolation():
    """Verify exact counts and strict namespace isolation for Phase A & Phase B (all 7 maps)."""
    index_path = ROOT / 'extensions' / 'hexen-map-exporter' / 'hoyolab-index.json'
    assert index_path.exists()
    index_data = json.loads(index_path.read_text(encoding='utf-8'))
    mapping = index_data['mapping']

    by_map = {'2': 0, '7': 0, '9': 0, '34': 0, '36': 0, '37': 0, '40': 0}
    for key in mapping:
        map_id = key.split(':')[0]
        assert map_id in by_map, f"Unexpected map_id in index: {map_id}"
        by_map[map_id] += 1

    assert by_map['2'] == 4321, f"Map 2 must retain exactly 4321 pairs, got {by_map['2']}"
    assert by_map['9'] == 90, f"Map 9 (Chasm) must have exactly 90 pairs, got {by_map['9']}"
    assert by_map['34'] == 94, f"Map 34 (Bygone Eras) must have exactly 94 pairs, got {by_map['34']}"
    assert by_map['36'] == 51, f"Map 36 (Sacred Mountain) must have exactly 51 pairs, got {by_map['36']}"
    assert by_map['7'] == 186, f"Map 7 (Enkanomiya) must have exactly 186 pairs, got {by_map['7']}"
    assert by_map['37'] == 47, f"Map 37 (Temple of Space) must have exactly 47 pairs, got {by_map['37']}"
    assert by_map['40'] == 148, f"Map 40 (Frost Moon) must have exactly 148 pairs, got {by_map['40']}"
    assert sum(by_map.values()) == 4937
