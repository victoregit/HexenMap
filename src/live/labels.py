def normalized(value):
    return ''.join(c for c in unicodedata.normalize('NFKD',value.casefold()) if not unicodedata.combining(c))


def portuguese_label(name, source=''):
    if source in SOURCE_PT: return SOURCE_PT[source]
    if name in SOURCE_PT: return SOURCE_PT[name]
    if not re.search('[\u3400-\u9fff]',name): return name
    return None


